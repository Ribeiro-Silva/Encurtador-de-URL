CREATE DATABASE IF NOT EXISTS encurtador CHARACTER SET utf8mb4;
USE encurtador;

CREATE TABLE IF NOT EXISTS links (
    id           BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    url_original VARCHAR(2048) NOT NULL,
    cliques      INT UNSIGNED NOT NULL DEFAULT 0,
    criado    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE USER IF NOT EXISTS 'user'@'localhost' IDENTIFIED BY 'trocar_senha';
GRANT SELECT, INSERT, UPDATE ON encurtador.* TO 'user'@'localhost';
FLUSH PRIVILEGES;